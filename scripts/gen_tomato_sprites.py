def overlay(base: list[str], plant_rows: list[str], y_offset: int = 0) -> list[str]:
    """`plant_rows` を `base` の上に y_offset から重ねる. 透明 '.' は維持."""
    out = [list(row) for row in base]
    for dy, src in enumerate(plant_rows):
        y = y_offset + dy
        if not (0 <= y < SIZE):
            continue
        for x, ch in enumerate(src):
            if x >= SIZE:
                break
            if ch != ".":
                out[y][x] = ch
    return ["".join(row) for row in out]


