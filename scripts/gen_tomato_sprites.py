def render(rows: list[str]) -> Image.Image:
    """ASCII グリッドを PNG イメージへ."""
    img = Image.new("RGBA", (SIZE, SIZE), PALETTE["."])
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            color = PALETTE.get(ch, PALETTE["."])
            img.putpixel((x, y), color)
    return img


def save(name: str, img: Image.Image, out_dir: str) -> str:
    path = os.path.join(out_dir, name)
    img.save(path, "PNG")
    return path


def gen_palette_image() -> Image.Image:
    """採用したパレットを 1 行ずつのカラーチップ画像として出力 (確認用)."""
    chip = 16
    keys = [k for k in PALETTE if k != "."]
    img = Image.new("RGBA", (chip * len(keys), chip), (255, 255, 255, 255))
    for i, k in enumerate(keys):
        for y in range(chip):
            for x in range(chip):
                img.putpixel((i * chip + x, y), PALETTE[k])
    return img


def gen_preview(images: list[Image.Image]) -> Image.Image:
    """4ステージを横並びにし 4 倍拡大した確認用プレビュー."""
    scale = 4
    margin = 4
    w = (SIZE * scale + margin) * len(images) + margin
    h = SIZE * scale + margin * 2
    preview = Image.new("RGBA", (w, h), (244, 240, 232, 255))
    for i, img in enumerate(images):
        big = img.resize((SIZE * scale, SIZE * scale), Image.NEAREST)
        preview.paste(big, (margin + i * (SIZE * scale + margin), margin), big)
    return preview


def main() -> None:
    out_dir = os.path.join(os.path.dirname(__file__), "..", "assets", "sprites", "tomato")
    out_dir = os.path.normpath(out_dir)
    os.makedirs(out_dir, exist_ok=True)

    stages = [
        ("stage1_seedling.png", overlay(SOIL_ROWS, STAGE1_PLANT)),
        ("stage2_growing.png", overlay(SOIL_ROWS, STAGE2_PLANT)),
        ("stage3_flowering.png", overlay(SOIL_ROWS, STAGE3_PLANT)),
        ("stage4_fruiting.png", overlay(SOIL_ROWS, STAGE4_PLANT)),
    ]

    images = []
    for name, rows in stages:
        img = render(rows)
        path = save(name, img, out_dir)
        print(f"wrote {path}")
        images.append(img)

    palette_img = gen_palette_image()
    save("palette.png", palette_img, out_dir)
    print(f"wrote {os.path.join(out_dir, 'palette.png')}")

    preview = gen_preview(images)
    save("preview.png", preview, out_dir)
    print(f"wrote {os.path.join(out_dir, 'preview.png')}")


if __name__ == "__main__":
    main()
